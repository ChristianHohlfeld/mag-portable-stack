#!/usr/bin/env bash
# Installs the NUMA hot-swap tool. Does NOT stop, start or swap any model:
# it only installs the binary, the sudoers rule for the room user, the state
# directory (seeded from the units that are running now) and the room env.
#   sudo bash ops/numa/install.sh [--dry-run]
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
DRY=0; [[ ${1:-} == --dry-run ]] && DRY=1
run(){ if (( DRY )); then echo "+ $*"; else "$@"; fi; }
ROOM_USER=${MAG_ROOM_USER:-magbot}
LIB=/usr/local/lib/mag-numa
STATE_DIR=/var/lib/mag-numa
CATALOG=${MAG_NUMA_CATALOG:-/opt/mag-stack/current/ops/numa/catalog.json}
BIN=${MAG_NUMA_BIN:-$ROOT/build/mag-numa-swap}
[[ -x $BIN ]] || { echo "build first: $BIN missing" >&2; exit 2; }

run install -d -m 0755 "$LIB" "$STATE_DIR" /etc/mag-stack
run install -m 0755 -o root -g root "$BIN" "$LIB/.mag-numa-swap.next"
run mv -f "$LIB/.mag-numa-swap.next" "$LIB/mag-numa-swap"

# The room may run exactly "mag-numa-swap swap <node> <model>" as root, nothing else.
rule="$ROOM_USER ALL=(root) NOPASSWD: $LIB/mag-numa-swap swap *"
if (( DRY )); then echo "+ write /etc/sudoers.d/mag-numa: $rule"; else
  tmp=$(mktemp); printf '%s\n' "# Generated by ops/numa/install.sh" "$rule" > "$tmp"
  visudo -cf "$tmp" >/dev/null && install -m 0440 "$tmp" /etc/sudoers.d/mag-numa; rm -f "$tmp"
fi

# Seed the state from what serves today (no unit is touched).
if [[ ! -s $STATE_DIR/state.json ]]; then
  n1=deepseek-v4-flash-0731-iq3
  systemctl is-active --quiet mag-llm-qwen.service 2>/dev/null && n1=qwen3.8-flash-next-uncensored
  seed="{\"nodes\":{\"0\":{\"model\":\"deepseek-v4-flash-0731\",\"state\":\"serving\",\"progress\":100},\"1\":{\"model\":\"$n1\",\"state\":\"serving\",\"progress\":100}}}"
  if (( DRY )); then echo "+ seed $STATE_DIR/state.json: $seed"; else printf '%s\n' "$seed" > "$STATE_DIR/state.json"; chmod 0644 "$STATE_DIR/state.json"; fi
fi
if (( DRY )); then echo "+ write /etc/mag-stack/numa.env (MAG_NUMA_CATALOG=$CATALOG)"; else
  printf 'MAG_NUMA_CATALOG=%s\nMAG_NUMA_STATE=%s/state.json\n' "$CATALOG" "$STATE_DIR" > /etc/mag-stack/numa.env
fi
echo "mag-numa installed. Restart the room (mag-120) to enable the NUMA model selector; models keep running."
