#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const source=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const api=source('native/api.hpp'),ui=source('web/app/files.js');
const section=api.slice(api.indexOf('void files_zip('),api.indexOf('// ---- the bots\' sites'));
assert(section.includes('::open(temp.c_str()'), 'ZIP must be created before response');
assert(section.includes('zipwrite('));
assert(section.includes('http::send_file(fd, r, target, "application/zip", h)'),'Serve immutable target through Range-aware send_file');
assert(section.includes('::rename(temp.c_str(), target.c_str())'),'Only publish complete snapshots');
assert(section.includes('0x06064b50') && section.includes('0x07064b50'),'ZIP64 EOCD and locator');
assert(section.includes('le(extra, 0x0001, 2)'),'ZIP64 extra fields');
assert(section.includes('"ETag", etag'),'Strong snapshot validator');
assert(section.includes('410, "ZIP-Download abgelaufen'),'Expired partials fail closed');
assert(section.includes('unlink(temp.c_str())'));
assert(!section.includes('http::write_all(fd,'),'no direct streaming ZIP');
assert(api.includes('filename=\\\"') || api.includes('filename=\\\"'), 'quoted ASCII filename');
assert(api.includes('filename*=UTF-8'), 'RFC5987 name preserved');
assert(ui.includes("const zip = el('a'"), 'native browser download without blob');
assert(ui.includes("zip.href = '/api/files.zip?snapshot='"), 'download manager receives immutable URL');
assert(!ui.includes('response.blob()'), 'large ZIP never duplicated in page memory');
assert(!ui.includes('URL.createObjectURL(blob)'), 'no synthetic blob download');
console.log('ZIP: temp-file Range response, dual Content-Disposition, single fetch and toast OK');
