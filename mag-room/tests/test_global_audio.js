#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {JSDOM}=require('jsdom');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const w=new JSDOM('<!doctype html><body><video id=a></video><audio id=b></audio></body>',
 {url:'https://mag.test/',runScripts:'outside-only'}).window;
let played=0,paused=0;
w.HTMLMediaElement.prototype.pause=function(){this._paused=true;paused++;};
w.HTMLMediaElement.prototype.play=function(){this._paused=false;played++;this.dispatchEvent(new w.Event('play'));return Promise.resolve()};
Object.defineProperty(w.HTMLMediaElement.prototype,'paused',{get(){return this._paused!==false}});
w.MAG={};
w.eval(read('web/app/audio.js'));
const {MAG}=w,a=w.document.querySelector('#a'),b=w.document.querySelector('#b');
let stopped=0;
MAG.audio.activate('tts',{name:'tts',stop:()=>stopped++});
assert.equal(MAG.audio.state(),'playing');
b.play();
assert.equal(stopped,1,'native media stops TTS');
a.play();
assert(b.paused,'playing video stops prior audio');
MAG.audio.stop();
assert(a.paused,'Stop pauses native video immediately');
assert.equal(MAG.audio.state(),'stopped');
let stops=0;
MAG.audio.activate('new',{name:'tts',stop:()=>stops++});
MAG.audio.stop();MAG.audio.stop();
assert.equal(stops,1,'stop is idempotent even while loading');
const tts=read('web/app/speak.js'),chat=read('web/app/messages.js');
assert(tts.includes("MAG.on('delta', updateLive)"),'read live text on every token');
assert(tts.includes("feed(pb,pb.text,m.state==='streaming')"),'complete last partial sentence on done');
assert(tts.includes("pb.nativeSettle(false)"),'stopping native audio releases pending play');
assert(tts.includes("button.innerHTML = playing ? MAG.icons.stop"),'loading remains explicit stop icon');
assert(tts.includes("const parts = (m.parts || []).filter(p=>p.k==='text')"),'streaming text not m.text only');
assert(chat.includes("spokenText(m).trim()"),'streaming action appears on first delta');
assert(chat.includes("m.state !== 'streaming') row.append(button('dots'"),'delete not offered while streaming');
assert(tts.includes('HTMLAudioElement')||tts.includes('new Audio()'),'Android screen-off native sink');
w.close();
console.log('global audio + live TTS: one source, stop, stream text, Android sink, idle cleanup OK');
